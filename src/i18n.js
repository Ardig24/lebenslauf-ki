/**
 * Get UI translations for a language code.
 * Falls back to English for missing keys.
 */
export function getUITranslations(langCode) {
    const lang = UI_TRANSLATIONS[langCode] || {};
    const fallback = UI_TRANSLATIONS.en;
    
    // Return a proxy that falls back to English for missing keys
    return new Proxy(lang, {
        get(target, prop) {
            return target[prop] || fallback[prop] || prop;
        }
    });
}

/**
 * Get translations for a language code.
 * Falls back to English for missing languages.
 */
export function getTranslations(langCode) {
    return TRANSLATIONS[langCode] || TRANSLATIONS.en;
}

/**
 * Generate a generic translation for languages not explicitly defined.
 * Returns English as fallback, but with appropriate placeholder names.
 */
export function getFallbackTranslations(langCode) {
    // For languages without full translations, use English
    return TRANSLATIONS[langCode] || TRANSLATIONS.en;
}

